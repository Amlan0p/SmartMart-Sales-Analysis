def chapter_title(document, text: str, in_toc: bool = True) -> None:
    """Chapter heading. Front-matter pages that must not appear in the TOC
    field (Table of Contents / List of Figures) use a styled paragraph."""
    if in_toc:
        heading = add_heading(document, text, 1)
        # Continuous flow: only front matter, chapter 1 and Appendix A start a new page.
        if text in ("Acknowledgement", "Abstract") or text.startswith(("1. ",)):
            heading.paragraph_format.page_break_before = True
            heading.paragraph_format.space_before = Pt(0)
        return
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.page_break_before = True
    paragraph.paragraph_format.space_after = Pt(14)
    paragraph.paragraph_format.keep_with_next = True
    run = paragraph.add_run(text)
    run.bold = True
    run.font.size = Pt(22)
    run.font.color.rgb = BLUE


