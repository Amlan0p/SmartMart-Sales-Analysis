        ["Columns (raw / cleaned)", f"{ctx.raw.shape[1]} / {df.shape[1]}"],
        ["Date range", f"{df['Order_Date'].min():%Y-%m-%d} to {df['Order_Date'].max():%Y-%m-%d}"],
        ["Distinct customers", whole(df["Customer_ID"].nunique())],
        ["Distinct products / categories", f"{df['Product'].nunique()} / {df['Category'].nunique()}"],
        ["Regions / cities (incl. 'Unknown')", f"{df['Region'].nunique()} / {df['City'].nunique()}"],
