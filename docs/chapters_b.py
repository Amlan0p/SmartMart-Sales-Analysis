# Chapter 12 - Monthly and year-over-year analysis
# --------------------------------------------------------------------------
def ch12_monthly(document, ctx: DocContext) -> None:
    monthly = ctx.results["monthly"]["monthly_table"].copy()
    yoy = ctx.results["yoy"]["yearly_table"]
    chapter_title(document, "12. Monthly and Year-over-Year Analysis")
    add_heading(document, "12.1 Monthly revenue", 2)
    monthly["MoM"] = monthly["Revenue"].pct_change() * 100
    rows = [[r.Period, money(r.Revenue, 0), whole(r.Orders), money(r.Average_Order_Value, 0),
             "" if pd.isna(r.MoM) else f"{r.MoM:+.1f}%"] for r in monthly.itertuples()]
    add_table(document, ["Month", "Revenue", "Orders", "Avg order value", "Change vs prior month"], rows,
              [3.8, 3.6, 2.2, 3.4, 3.6], align=["l", "r", "r", "r", "r"],
              caption=ctx.next_table("Monthly sales (src/analysis.py: monthly_sales_analysis; the last column is calculated for this report)"), font_size=9)
    add_figure(document, ctx.chart("monthly_revenue_trend.png"), ctx.next_figure("Monthly revenue trend (src/visualization.py: plot_monthly_revenue)"), width_cm=15.5, max_height_cm=8.0)
    peak, low = ctx.results["monthly"]["peak_month"], ctx.results["monthly"]["lowest_month"]
    q4 = {y: monthly[(monthly.Year == y) & (monthly.Month >= 10)].Revenue.sum() / monthly[monthly.Year == y].Revenue.sum() * 100 for y in monthly.Year.unique()}
    finding(document, f"Revenue peaked in {peak} ({money(monthly.Revenue.max(), 0)}) and was lowest in {low} ({money(monthly.Revenue.min(), 0)}). "
            + " ".join(f"October-December accounts for {pct(v)} of {int(y)} revenue." for y, v in q4.items()))
    interpretation(document, "Demand is clearly seasonal, with an autumn build-up and a strong festive-season peak; this is expected because the "
                   "generator applies a festive uplift (Chapter 6). January 2024 is a second high point, while February is among the "
                   "lowest-revenue months in both years. Because the data is synthetic, the seasonality reflects the generator's design, not a real market.")
    add_heading(document, "12.2 Year-over-year comparison", 2)
    rows = []
    for r in yoy.itertuples():
        g = "" if pd.isna(r.Revenue_Growth_Percent) else f"{r.Revenue_Growth_Percent:+.1f}%"
        o = "" if pd.isna(r.Order_Growth_Percent) else f"{r.Order_Growth_Percent:+.1f}%"
        q = "" if pd.isna(r.Quantity_Growth_Percent) else f"{r.Quantity_Growth_Percent:+.2f}%"
        rows.append([int(r.Year), money(r.Revenue, 0), whole(r.Orders), whole(r.Quantity), g, o, q])
    add_table(document, ["Year", "Revenue", "Orders", "Units", "Revenue growth", "Order growth", "Unit growth"], rows,
              [1.6, 3.6, 2.0, 2.0, 2.8, 2.4, 2.2], align=["c", "r", "r", "r", "r", "r", "r"],
              caption=ctx.next_table("Year-over-year comparison (src/analysis.py: year_over_year_analysis)"), font_size=9.5)
    last = yoy.iloc[-1]
    finding(document, f"Revenue grew {last.Revenue_Growth_Percent:.1f}% from {int(yoy.iloc[0].Year)} to {int(last.Year)}, while orders grew "
            f"{last.Order_Growth_Percent:.1f}% and units sold {last.Quantity_Growth_Percent:.2f}%.")
    interpretation(document, "Almost all of the growth came from a higher revenue per order; order and unit growth were marginal. "
                   "If management wants volume growth, the data shows very little of it yet.")
    add_heading(document, "12.3 Implementation", 2)
    add_code(document, "src/analysis.py - monthly_sales_analysis", ctx.function_source("src/analysis.py", "monthly_sales_analysis", with_docstring=False), font_size=8)
    add_code(document, "src/analysis.py - year_over_year_analysis", ctx.function_source("src/analysis.py", "year_over_year_analysis", with_docstring=False), font_size=8)
    add_paragraph(document, "Monthly analysis groups by year and month, builds a readable `Period` label and records the peak and lowest months. "
                  "The year-over-year function aggregates by year and uses `pct_change`; it also reports whether comparable periods "
                  "exist, so the Excel and insight modules never claim growth from a single year of data.")


