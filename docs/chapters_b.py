    add_paragraph(document, "**Logic.** Revenue is a sum, orders and customers use `nunique` so repeated rows cannot be double-counted, and "
                  "both averages use `safe_divide` (from `utils.py`), which returns 0 instead of raising when a denominator is zero. "
                  "Note that Average Selling Price is a **weighted** average (revenue \u00F7 units), not the mean of the Unit_Price column.")
